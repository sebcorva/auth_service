CREATE TABLE usuarios (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR2(100) NOT NULL,
    apellido        VARCHAR2(100) NOT NULL,
    email           VARCHAR2(150) NOT NULL,
    password_hash   VARCHAR2(60)  NOT NULL,
    rol             VARCHAR2(20)  NOT NULL,
    premium         NUMBER(1)     NOT NULL,
    fecha_registro  TIMESTAMP(6)  NOT NULL,
    CONSTRAINT pk_usuarios PRIMARY KEY (id),
    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('ADMIN', 'USUARIO')),
    CONSTRAINT ck_usuarios_premium CHECK (premium IN (0, 1))
);

CREATE TABLE pagos (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    usuario_id  NUMBER       NOT NULL,
    monto       NUMBER(10)   NOT NULL,
    fecha       TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_pagos PRIMARY KEY (id),
    CONSTRAINT fk_pagos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

